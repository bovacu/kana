# fude/zoom/hand_maths.h from the Hershey fonts' maths and Greek sets (mathlow.jhf, mathupp.jhf, greeks.jhf, beside
# this): each symbol a formula is written with by hand (handmath.h), by its Unicode code point.
#
#   python3 tools/hershey/hand_maths.py

import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'fude', 'zoom', 'hand_maths.h')


def parse(name):
    """A .jhf file's glyphs, ASCII 32 on: (left, right, strokes of (x, y) — y down)."""
    text = ''.join(l for l in open(os.path.join(HERE, name + '.jhf')).read().replace('\r', '').split('\n') if l.strip())
    glyphs, i = [], 0
    while i < len(text):
        count = int(text[i + 5:i + 8])
        data = text[i + 8:i + 8 + count * 2]
        i += 8 + count * 2
        strokes, cur = [], []
        for k in range(2, len(data), 2):
            if data[k:k + 2] == ' R':
                strokes.append(cur)
                cur = []
            else:
                cur.append((ord(data[k]) - ord('R'), ord(data[k + 1]) - ord('R')))
        strokes.append(cur)
        glyphs.append((ord(data[0]) - ord('R'), ord(data[1]) - ord('R'), [s for s in strokes if s]))
    return glyphs


FONTS = {n: parse(n) for n in ('mathlow', 'mathupp', 'greeks')}

# code point → (set, its ASCII place there)
MAP = {}
for c in '0123456789':
    MAP[ord(c)] = ('mathlow', ord(c))
for k in range(26):
    MAP[ord('a') + k] = ('mathlow', 65 + k)   # (mathlow's letters are small ones)
    MAP[ord('A') + k] = ('mathupp', 65 + k)
for cp, a in {'+': 43, '=': 61, '<': 60, '>': 62, '(': 40, ')': 41, ',': 44, '.': 46, '/': 47, '[': 91, ']': 93, '{': 123,
              '}': 125, '%': 37, '*': 42, '\\': 92}.items():
    MAP[ord(cp)] = ('mathlow', a)
MAP[ord('-')] = ('mathlow', 45)
for cp, a in {0x2212: 45, 0x00B1: 33, 0x2213: 34, 0x00D7: 35, 0x22C5: 36, 0x00B7: 36, 0x2264: 38, 0x2265: 39, 0x2217: 42,
              0x220F: 58, 0x2211: 59, 0x2260: 63, 0x2261: 64, 0x221D: 94, 0x221E: 95, 0x00B0: 96, 0x221A: 99, 0x2282: 100,
              0x222A: 101, 0x2283: 102, 0x2229: 103, 0x2208: 104, 0x2192: 105, 0x2191: 106, 0x2190: 107, 0x2193: 108,
              0x2202: 109, 0x2207: 110, 0x222B: 113, 0x2203: 118, 0x00F7: 120, 0x2016: 121, 0x2225: 121, 0x22A5: 122,
              0x2220: 124, 0x2234: 126, 0x223C: 127, ord('~'): 127, 0x2135: 119}.items():
    MAP[cp] = ('mathlow', a)
for cp, a in {'!': 33, ':': 58, ';': 59, '?': 63, '|': 124, "'": 39}.items():
    MAP[ord(cp)] = ('greeks', ord(cp))
MAP[0x2032] = ('greeks', 39)   # ′ (a prime: an apostrophe's stroke)
MAP[0xE000] = ('mathlow', 112)  # (private: ∫ written small — the reader's second shape for it)
MAP[0xE001] = ('mathlow', 98)   # (private: √ written small)
MAP[0x2223] = ('greeks', 124)  # ∣
# Greek: its capitals as the Latin ones where they are the same, the others (and every small one) from greeks.jhf.
HERSHEY_GREEK = 'ABCDEFGHIJKLMNOPQRSTUVWX'   # (where greeks.jhf has them)
for k in range(24):
    cap = 0x0391 + k + (1 if k >= 17 else 0)   # (no U+03A2)
    MAP[cap] = ('greeks', ord(HERSHEY_GREEK[k]))
    MAP[0x03B1 + k + (1 if k >= 17 else 0)] = ('greeks', ord(HERSHEY_GREEK[k].lower()))
MAP[0x03C2] = ('greeks', ord('r'))   # ς as σ
MAP[0x03D1] = ('greeks', ord('h'))   # ϑ
MAP[0x03D5] = ('greeks', ord('u'))   # ϕ
MAP[0x03F5] = ('greeks', ord('e'))   # ϵ

cps = sorted(MAP)
starts, points, boxes = [0], [], []
for cp in cps:
    font, a = MAP[cp]
    left, right, strokes = FONTS[font][a - 32]
    xs = [x for s in strokes for x, _ in s]
    ys = [y for s in strokes for _, y in s]
    for si, s in enumerate(strokes):
        if si > 0:
            points += [-128, -128]
        for x, y in s:
            points += [x, y]
    starts.append(len(points))
    boxes.append((left, right))
    assert all(-127 <= v <= 127 or v == -128 for v in points[starts[-2]:])

HEADER = '''// Copyright (c) 2026 Borja Vazquez Cuesta. All rights reserved.

#ifndef FUDE_ZOOM_HAND_MATHS_H
#define FUDE_ZOOM_HAND_MATHS_H

// ===========================================================================
// Hand maths: the shapes of the symbols a formula is written with by hand (zoom/handmath.h), taken from the Hershey
// fonts' maths and Greek sets, as tables of our own.
//
// Where it sits: zoom, the canvas apps' layer; only handmath.c includes it. It is data only: static constant tables.
// Threads: the tables are constant, so they are safe to read from any thread.
// Files: GENERATED by tools/hershey/hand_maths.py from mathlow.jhf, mathupp.jhf and greeks.jhf (beside the script):
//   run `python3 tools/hershey/hand_maths.py` to make it again. Do not edit it by hand, since the script rewrites the
//   whole file, these comments included. The script also chooses which code point takes which Hershey glyph.
// The format, in font units:
//   FUDE_ZOOM_HAND_MATHS symbols. FUDE_ZOOM_HAND_MATHS_CP holds their Unicode code points in ascending order, so a
//   symbol is found by binary search; U+E000 and U+E001 are private ones for ∫ and √ written small.
//   FUDE_ZOOM_HAND_MATHS_BEARINGS: each symbol's left and right bearings.
//   FUDE_ZOOM_HAND_MATHS_STARTS: where each symbol's points begin in FUDE_ZOOM_HAND_MATHS_POINTS; the next entry is
//   where they end.
//   FUDE_ZOOM_HAND_MATHS_POINTS: x, y pairs with y down, the baseline at 9 and a capital's top at -12. A -128, -128
//   pair lifts the pen between two strokes.
// Licence: the acknowledgement below must stay with the data.
//   The Hershey Fonts were originally created by Dr. A. V. Hershey while working at the U. S. National Bureau of
//   Standards. The format of the Font data in this distribution was originally created by James Hurt, Cognition,
//   Inc., 900 Technology Park Drive, Billerica, MA 01821 (mit-eddie!ci-dandelion!hurt).
// ===========================================================================

'''

with open(OUT, 'w') as f:
    # The header's overview (zoom/hand_maths.h), written whole: edit it here, never in the header.
    f.write(HEADER)
    f.write('#define FUDE_ZOOM_HAND_MATHS %du\n' % len(cps))

    def table(decl, values, per):
        f.write(decl + ' = {\n')
        for i in range(0, len(values), per):
            f.write('    ' + ', '.join(values[i:i + per]) + ',\n')
        f.write('};\n')

    table('static const u32 FUDE_ZOOM_HAND_MATHS_CP[FUDE_ZOOM_HAND_MATHS]', ['0x%04X' % c for c in cps], 12)
    table('static const i8 FUDE_ZOOM_HAND_MATHS_BEARINGS[FUDE_ZOOM_HAND_MATHS][2]', ['{ %d, %d }' % b for b in boxes], 8)
    table('static const u16 FUDE_ZOOM_HAND_MATHS_STARTS[FUDE_ZOOM_HAND_MATHS + 1u]', [str(s) for s in starts], 16)
    table('static const i8 FUDE_ZOOM_HAND_MATHS_POINTS[%d]' % len(points), [str(p) for p in points], 24)
    f.write('\n#endif\n')
print('%d symbols, %d bytes of points -> %s' % (len(cps), len(points), os.path.normpath(OUT)))
